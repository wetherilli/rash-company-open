/* =====================================================================
 *  라슈 컴퍼니 — 특정 배정 (픽업)
 * ---------------------------------------------------------------------
 *  상점의 「인격 배정」 옆에 하나 더 서는 창구입니다.
 *  이름에 지정한 말이 든 인격·교육위원이 눈에 띄게 자주 나옵니다.
 *
 *  판이 바뀔 때마다 아래 tag 와 name 만 갈아 끼우면 됩니다.
 *  잠시 닫아 두려면 on 을 false 로.
 *
 *  ■ 적는 법
 *    tag   찾을 말. 인격 제목이나 교육위원 제목에 이 말이 들어 있으면 대상입니다.
 *          여러 개면 배열로 —  tag: ["아라온호", "U사"]
 *    rate  한 번 뽑을 때 이 확률로 대상 쪽에서 먼저 고릅니다.
 *          (성급을 정하는 확률은 그대로입니다. 같은 ★★ 안에서 누가 나올지가 달라집니다)
 *    cost  1회 비용. 안 적으면 일반 배정과 같은 값을 씁니다.
 *    line   이 판의 광고 문구. 상점 칸과 배정 화면에 크게 걸립니다.
 *    banner 문구 뒤에 깔릴 그림. assets/scene 의 배경을 그대로 써도 됩니다.
 *    desc  무엇이 자주 나오는지 한 줄 설명.
 * ===================================================================== */

